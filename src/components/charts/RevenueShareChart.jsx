import React from "react";
import { Cell, Legend, Pie, PieChart, ResponsiveContainer, Tooltip } from "recharts";
import ChartCard from "@/components/charts/ChartCard";
import { TOOLTIP_STYLE, inrFormatter } from "@/lib/chartTheme";
import { formatPercent } from "@/lib/format";

export default function RevenueShareChart({ segments = [] }) {
  const data = segments.filter((s) => s.share_of_revenue > 0);

  return (
    <ChartCard
      title="Revenue contribution by segment"
      description="Share of total net revenue generated by each segment."
      empty={!data.length}
    >
      <ResponsiveContainer width="100%" height={300}>
        <PieChart>
          <Pie
            data={data}
            dataKey="revenue"
            nameKey="label"
            innerRadius={62}
            outerRadius={96}
            paddingAngle={2}
            stroke="#ffffff"
            strokeWidth={2}
          >
            {data.map((entry) => (
              <Cell key={entry.segment} fill={entry.color} />
            ))}
          </Pie>
          <Tooltip
            contentStyle={TOOLTIP_STYLE}
            formatter={(value, name, payload) => [
              `${inrFormatter(value)} · ${formatPercent(payload.payload.share_of_revenue)}`,
              payload.payload.label
            ]}
          />
          <Legend wrapperStyle={{ fontSize: 11 }} verticalAlign="bottom" height={44} />
        </PieChart>
      </ResponsiveContainer>
    </ChartCard>
  );
}